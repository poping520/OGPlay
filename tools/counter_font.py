#!/usr/bin/env python3
"""Generates src/frontend/counter_font.inc: the frame-rate counter's digits as a tiny static TrueType font.

Source: the SN Pro variable font the launcher already bundles (webui/apps/gui/assets/fonts, OFL-1.1). The font is
fixed at SemiBold, its tabular figures (tnum) take the digit code points so the counter does not shift as values
change, and only 0-9 and '-' are kept. Requires fontTools (pip install fonttools); the output is checked in, so
builds do not need it.

Usage: python3 tools/counter_font.py
"""
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "webui/apps/gui/assets/fonts/sn-pro-wght.ttf"
OUTPUT = ROOT / "src/frontend/counter_font.inc"
WEIGHT = 600
CHARACTERS = "0123456789-"


def tabular_figures(font: TTFont) -> dict[str, str]:
    """Digit glyph -> its tnum alternate, from the font's single substitutions."""
    gsub = font["GSUB"].table
    mapping: dict[str, str] = {}
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag != "tnum":
            continue
        for index in record.Feature.LookupListIndex:
            for table in gsub.LookupList.Lookup[index].SubTable:
                table = getattr(table, "ExtSubTable", table)
                mapping.update(getattr(table, "mapping", {}) or {})
    return mapping


def main() -> None:
    font = instancer.instantiateVariableFont(TTFont(SOURCE), {"wght": WEIGHT})
    tnum = tabular_figures(font)
    for table in font["cmap"].tables:
        for code in [ord(digit) for digit in "0123456789"]:
            if code in table.cmap and table.cmap[code] in tnum:
                table.cmap[code] = tnum[table.cmap[code]]
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.name_IDs = [0, 13, 14]  # copyright and the OFL notice travel with the font
    options.notdef_outline = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=map(ord, CHARACTERS))
    subsetter.subset(font)
    data = io.BytesIO()
    font.save(data)
    blob = data.getvalue()
    lines = [", ".join(f"0x{byte:02x}" for byte in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    OUTPUT.write_text(
        "// Generated by tools/counter_font.py from SN Pro (Copyright 2024 The SN Pro Project Authors,\n"
        f"// SIL Open Font License 1.1): SemiBold ({WEIGHT}), tabular figures, '{CHARACTERS}' only. Do not edit.\n"
        + ",\n".join(lines) + "\n",
        encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(blob)} bytes")


if __name__ == "__main__":
    main()
