#!/usr/bin/env python3
"""Writes the GBK (CP936) double-byte table used to decode legacy ZIP entry names.

Index = (lead - 0x81) * 191 + (trail - 0x40) for lead 0x81..0xFE, trail 0x40..0xFE; 0 marks an unmapped pair.
Python's own codec is the source, so every host decodes archive names the same way."""
import argparse
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    values = []
    for lead in range(0x81, 0xFF):
        for trail in range(0x40, 0xFF):
            try:
                text = bytes([lead, trail]).decode("gbk")
                values.append(ord(text) if len(text) == 1 and ord(text) <= 0xFFFF else 0)
            except UnicodeDecodeError:
                values.append(0)
    lines = ["// Generated by tools/generate_gbk_table.py; do not edit.", "#pragma once", "#include <cstdint>",
             "namespace ogplay::app::generated {",
             f"inline constexpr std::uint16_t kGbkTable[{len(values)}] = {{"]
    for start in range(0, len(values), 16):
        lines.append("    " + ", ".join(f"0x{value:04x}" for value in values[start:start + 16]) + ",")
    lines += ["};", "}  // namespace ogplay::app::generated", ""]
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
